    private void buttonRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonRegistrarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombre.getText();
        String telefono = txtTelefono.getText();
        Rol rol = Rol.valueOf((String) comboRol.getSelectedItem());
        
        if(nombre.isEmpty() || telefono.isEmpty() || rol == null) {
            JOptionPane.showMessageDialog(panel, "Llena todos los campos.");
        } else {
            if(rol.equals(Rol.CLIENTE)) {
                Cliente cliente = new Cliente(nombre, telefono, rol);
                
                boolean registroExitoso = Auth.registrar(cliente, panel);
                
                if(!registroExitoso)
                    card.show(panel, "login");
                
            } else {
                Administrador admin = new Administrador(nombre, telefono, rol);
                
                boolean registroExitoso = Auth.registrar(admin, panel);
                
                if(!registroExitoso)
                    card.show(panel, "login");
            }
        }
        
        txtNombre.setText("");
        txtTelefono.setText("");
    }//GEN-LAST:event_buttonRegistrarActionPerformed



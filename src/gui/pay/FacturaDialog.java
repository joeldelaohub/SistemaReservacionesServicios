    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        // TODO add your handling code here:
        int opcion = JOptionPane.showConfirmDialog(this, "Estas seguro del pago?", "Pago Factura", 2);
        
        if(opcion == 0) {
            try {
                double anticipo = Double.parseDouble(txtMonto.getText());
                Factura factura = new Factura(this.reserva,this.reserva.getPaquete().getPrecio(), anticipo);
                this.reserva.setFechaConfirmacion(LocalDateTime.now());
                GestionFactura.facturas.add(factura);
                
                this.reserva.confirmar();
                
                JOptionPane.showMessageDialog(this, "Reserva confirmada exitosamente!");
                this.dispose();
            }catch(NumberFormatException e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "Valor invalido", JOptionPane.WARNING_MESSAGE);
            }
            catch(IllegalArgumentException e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "Valor invalido", JOptionPane.WARNING_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed


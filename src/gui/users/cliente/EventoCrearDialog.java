    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        // TODO add your handling code here:
        int opcion = JOptionPane.showConfirmDialog(this, "Estas seguro de los cambios", "Realizar Modificacion", 2);
        
        if(opcion == 0) {
            String fecha = txtFecha.getText(); // obtenemos la fecha en texto
            LocalDate fechaEv = LocalDate.parse(fecha); // convertimos la fecha a LocalDate
            int duracionEv = 0; // inicializamos la duracion
            String ubicacion = txtUbicacion.getText(); // obtenemos la ubicacion en texto
            String tipoEv = txtTipoEv.getText(); // obtenemos el tipo de evento en texto
            int hora = Integer.parseInt((String) comboHora.getSelectedItem()); // convertimos la hora a tipo entero
            int minuto = Integer.parseInt((String) comboMinuto.getSelectedItem()); // convertimos el minuto a tipo entero
            LocalTime horaEv = LocalTime.of(hora, minuto); // unimos hora y minuto y lo convertimos en LocalTime
            
            
            // validamos que la duracion sea mayor a 0
            if((Integer) duracion.getValue() <= 0) {
                JOptionPane.showMessageDialog(this, "La duracion no puede ser menor o igual que cero", "Duracion Invalida", WARNING_MESSAGE);
            } else {
                duracionEv = (Integer) duracion.getValue();
            }
            
            // creamos el evento
            Evento evento = new Evento(fechaEv, duracionEv, ubicacion, tipoEv, horaEv);
            
            // validamos que el evento fue creado correctamente
            try {
                this.evento = evento;
                GestionEvento.eventos.add(evento);
                JOptionPane.showMessageDialog(this, "Evento creado!");
                this.dispose();
            } catch(IllegalArgumentException e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso", WARNING_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed



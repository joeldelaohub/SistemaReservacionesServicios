    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        // TODO add your handling code here:
        int opcion = JOptionPane.showConfirmDialog(this, "Estas seguro de los cambios", "Realizar Modificacion", 2);
        
        if(opcion == 0) {
            String fecha = txtFecha.getText();
            LocalDate fechaNueva = LocalDate.parse(fecha);
            int duracionEv = 0;
            String ubicacion = txtUbicacion.getText();
            String tipoEv = txtTipoEv.getText();
            int hora = Integer.parseInt((String) comboHora.getSelectedItem());
            int minuto = Integer.parseInt((String) comboMinuto.getSelectedItem());
            LocalTime horaEv = LocalTime.of(hora, minuto);
            Paquete paquete = this.paquete;
            
            if((Integer) duracion.getValue() <= 0) {
                JOptionPane.showMessageDialog(this, "La duracion no puede ser menor o igual que cero", "Duracion Invalida", WARNING_MESSAGE);
            } else {
                duracionEv = (Integer) duracion.getValue();
            }
            
            Evento evento = new Evento(fechaNueva, duracionEv, ubicacion, tipoEv, horaEv);
            
            try {
                if(GestorReserva.validarFecha(reserva, evento)) {
                    GestionEvento.modificarEvento(evento);
                    reserva.setEvento(evento);
                    reserva.setPaquete(paquete);
                    JOptionPane.showMessageDialog(this, "Modificacion Exitosa!");
                    this.dispose();
                }
            } catch(IllegalArgumentException e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso", WARNING_MESSAGE);
            }
            
             EventoCSV.guardarEventos();
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed



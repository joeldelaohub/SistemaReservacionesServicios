    public void llenarCombo(JComboBox combo1, JComboBox combo2) {
        String[] hora = new String[13];
        String[] minuto = {"00", "15", "30", "45"};
        
        for(int i = 0; i < 13; i++) {
            hora[i] = String.format("%02d", i);
        }
        
        combo1.setModel(new DefaultComboBoxModel<>(hora));
        combo2.setModel(new DefaultComboBoxModel<>(minuto));
    }


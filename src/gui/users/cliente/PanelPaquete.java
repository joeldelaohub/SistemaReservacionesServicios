    public PanelPaquete() {
        initComponents();
        this.setLayout(new FlowLayout(FlowLayout.CENTER, 15, 10));
        
        mostrarServicios();
    }
    
    public void mostrarServicios() {
        for(Paquete p: GestionPaquete.paquetes) {
            this.add(crearPanelServicio(p.getNombre()));
        }
    }
    
    public JPanel crearPanelServicio(String nombreServicio) {
       PanelTarjetaServicio tarjeta = new PanelTarjetaServicio(nombreServicio);
       
       panelServicios.add(tarjeta);
       
       tarjeta.addMouseListener(new MouseAdapter() {
           @Override
           public void mouseClicked(MouseEvent ev) {
               for(JPanel p: panelServicios) {
                   p.setBorder(BorderFactory.createEmptyBorder());
               }
               
               tarjeta.setBorder(BorderFactory.createLineBorder(new Color(59, 77, 240), 2));
               
               paqueteSeleccionado = GestionPaquete.buscarPaqueteNombre(tarjeta.getNombre());
           }
       });
       
       return tarjeta;
    }
    

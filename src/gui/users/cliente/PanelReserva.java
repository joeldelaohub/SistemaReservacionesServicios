    private void btnEnviarReservaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnviarReservaActionPerformed
        // TODO add your handling code here:
        
        if(this.evento == null || PanelPaquete.paqueteSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "No Hay evento o paquete seleccionado");
        
        } else {
            Reserva reserva = new Reserva((Cliente) Auth.usuarioLogueado, this.evento, PanelPaquete.paqueteSeleccionado,
                                            LocalDateTime.now());
            
            
            
            GestorReserva.agregarReserva(reserva);
            
            JOptionPane.showMessageDialog(this, "Reserva hecha con exito!");
            
            EventoCSV.guardarEventos();
            ReservaCSV.guardarReserva();
        }
    }//GEN-LAST:event_btnEnviarReservaActionPerformed



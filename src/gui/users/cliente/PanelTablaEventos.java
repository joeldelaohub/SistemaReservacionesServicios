    public void actualizarTabla() {
         modelo.setRowCount(0);
        
        for(Reserva e: GestorReserva.listaReservas) {
            Object[] reserva = new Object[]{
                e.getEvento().getFecha().toString(),
                e.getPaquete().getNombre(),
                e.getEstado(),
                e.getFechaLimitePago().toLocalDate().toString(),
                e.getFechaConfirmacion() == null ? "Sin Fecha" : e.getFechaConfirmacion().toLocalDate().toString()};
                modelo.addRow(reserva);
        }
    }


    public void actualizarTabla() {
         modelo.setRowCount(0);
        
        for(Servicio s: PanelPaquete.paqueteSeleccionado.getListaServicios()) {
            Object[] servicio = new Object[]{
                s.getNombre(),
                String.valueOf(s.getPrecio()),
                s.getDescripcion()
            };
            
            modelo.addRow(servicio);
        }
    }
    


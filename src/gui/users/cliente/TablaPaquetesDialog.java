    public Paquete getPaquete() {
        int opcion = tablaPaquete.getSelectedRow();
        
        Paquete paquete = GestionPaquete.paquetes.get(opcion);
        
        return paquete;
    }
    
    public void actualizarTabla() {
        modelo.setRowCount(0);
        
        for(Paquete p: GestionPaquete.paquetes) {
            Object[] paquete = new Object[] {p.getNombre(), p.getPrecio(), p.getCantidadServicios()};
            modelo.addRow(paquete);
        }
    }

